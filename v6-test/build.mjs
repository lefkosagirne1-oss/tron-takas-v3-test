import fs from "node:fs";
import solc from "solc";
import {createRequire} from "node:module";
import path from "node:path";
const require=createRequire(import.meta.url);
const source=fs.readFileSync("contracts/TakasV6Simple.sol","utf8");
const input={language:"Solidity",sources:{"TakasV6Simple.sol":{content:source}},settings:{optimizer:{enabled:true,runs:200},evmVersion:"paris",viaIR:true,outputSelection:{"*":{"*":["abi","evm.bytecode.object"]}}}};
const out=JSON.parse(solc.compile(JSON.stringify(input)));
const errors=(out.errors||[]).filter(x=>x.severity==="error");
if(errors.length)throw Error(errors.map(x=>x.formattedMessage).join("\n"));
const c=out.contracts["TakasV6Simple.sol"].TakasV6Simple;
if(!c?.evm?.bytecode?.object)throw Error("Missing bytecode");
const create=c.abi.find(x=>x.name==="create"&&x.type==="function");
const deposit=c.abi.find(x=>x.name==="deposit"&&x.type==="function");
if(create.inputs.length!==2||deposit.inputs.length!==4)throw Error("ABI mismatch");
fs.mkdirSync("v6-test/dist",{recursive:true});
fs.writeFileSync("v6-test/dist/TakasV6Simple.json",JSON.stringify({contractName:"TakasV6Simple",abi:c.abi,bytecode:c.evm.bytecode.object,network:"Nile",compiler:"solc 0.8.31"},null,2));
console.log("V6 compilation OK; bytecode bytes:",c.evm.bytecode.object.length/2);

const fixedSource=fs.readFileSync("contracts/TakasV7Fixed.sol","utf8");
const fixedInput={language:"Solidity",sources:{"TakasV7Fixed.sol":{content:fixedSource}},settings:{optimizer:{enabled:true,runs:200},evmVersion:"paris",viaIR:true,outputSelection:{"*":{"*":["abi","evm.bytecode.object"]}}}};
const fixedOut=JSON.parse(solc.compile(JSON.stringify(fixedInput)));
const fixedErrors=(fixedOut.errors||[]).filter(x=>x.severity==="error");
if(fixedErrors.length)throw Error(fixedErrors.map(x=>x.formattedMessage).join("\n"));
const fixed=fixedOut.contracts["TakasV7Fixed.sol"].TakasV7Fixed;
if(!fixed?.evm?.bytecode?.object)throw Error("Fixed commission bytecode missing");
fs.writeFileSync("v6-test/dist/TakasV6Fixed.json",JSON.stringify({contractName:"TakasV7Fixed",abi:fixed.abi,bytecode:fixed.evm.bytecode.object,network:"Nile",compiler:"solc 0.8.31"},null,2));
console.log("V6 fixed-commission compilation OK; bytecode bytes:",fixed.evm.bytecode.object.length/2);

const inviteSource=fs.readFileSync("contracts/TakasV8Invite.sol","utf8");
const inviteInput={language:"Solidity",sources:{"TakasV8Invite.sol":{content:inviteSource}},settings:{optimizer:{enabled:true,runs:200},evmVersion:"paris",viaIR:true,outputSelection:{"*":{"*":["abi","evm.bytecode.object"]}}}};
const compilerPath=path.resolve(process.env.TRON_SOLC_PATH||"v6-test/.cache/tron-soljson.cjs");
const tronSolc=solc.setupMethods(require(compilerPath));
if(!tronSolc.version().startsWith("0.8.31"))throw Error("Unexpected TRON compiler version: "+tronSolc.version());
const inviteOut=JSON.parse(tronSolc.compile(JSON.stringify(inviteInput)));
const inviteErrors=(inviteOut.errors||[]).filter(x=>x.severity==="error");
if(inviteErrors.length)throw Error(inviteErrors.map(x=>x.formattedMessage).join("\n"));
const invite=inviteOut.contracts["TakasV8Invite.sol"].TakasV8Invite;
if(!invite?.evm?.bytecode?.object)throw Error("Invite contract bytecode missing");
if(invite.abi.find(x=>x.name==="create")?.inputs?.length!==4||invite.abi.find(x=>x.name==="deposit")?.inputs?.length!==5||!invite.abi.some(x=>x.name==="inviteVersion"))throw Error("V8 ABI mismatch");
fs.writeFileSync("v6-test/dist/TakasV8Invite.json",JSON.stringify({contractName:"TakasV8Invite",abi:invite.abi,bytecode:invite.evm.bytecode.object,network:"Nile",compiler:"tron-solc 0.8.31"},null,2));
console.log("V8 secure invitation compilation OK; bytecode bytes:",invite.evm.bytecode.object.length/2);
